<?php

namespace Tests\Feature;

use App\Models\Facility;
use App\Models\FacilityCategory;
use App\Models\Reservation;
use App\Models\User;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Tests\TestCase;

class ReportUiTest extends TestCase
{
    use RefreshDatabase;

    private User $admin;

    protected function setUp(): void
    {
        parent::setUp();
        $this->admin = User::factory()->create([
            'role' => 'admin',
            'is_active' => true,
        ]);
    }

    public function test_admin_can_access_reports_master_list()
    {
        $response = $this->actingAs($this->admin)->get(route('admin.reports.index'));
        $response->assertOk();
        $response->assertSee('Reports &amp; Analytics', false);
        $response->assertSee('Master Reservation Register');
        $response->assertSee('Certified Signatories');
        $response->assertSee('Export CSV');
        $response->assertSee('Export PDF');
    }

    public function test_admin_can_access_all_report_tabs()
    {
        $tabs = [
            'income'        => 'Financial Statement &amp; Revenue Ledger',
            'facilities'    => 'Facility Utilization &amp; Venue Audit',
            'clients'       => 'Client Activity &amp; Booking Breakdown',
            'dispatch'      => 'Operations &amp; Setup Dispatch Checklist',
            'cancellations' => 'Cancellations &amp; Deposit Forfeiture Audit',
            'analytics'     => 'Executive Statistics &amp; Analytics',
        ];

        foreach ($tabs as $type => $expectedTitleFragment) {
            $response = $this->actingAs($this->admin)->get(route('admin.reports.index', ['report_type' => $type]));
            $response->assertOk();
            $response->assertSee($expectedTitleFragment, false);
        }
    }

    public function test_admin_can_filter_by_facility_and_grouped_mode()
    {
        $category = FacilityCategory::create(['name' => 'Main Halls']);
        $facility = Facility::factory()->create([
            'name' => 'Grand Auditorium',
            'category_id' => $category->id,
        ]);

        $response = $this->actingAs($this->admin)->get(route('admin.reports.index', [
            'report_type' => 'reservations',
            'facility_id' => $facility->id,
            'group_by'    => 'facility',
        ]));

        $response->assertOk();
        $response->assertSee('Grand Auditorium');
    }

    public function test_admin_can_export_csv()
    {
        $response = $this->actingAs($this->admin)->get(route('admin.reports.export-csv', [
            'report_type' => 'reservations',
        ]));

        $response->assertOk();
        $this->assertEquals('text/csv; charset=UTF-8', $response->headers->get('content-type'));
    }

    public function test_admin_can_access_print_view()
    {
        $response = $this->actingAs($this->admin)->get(route('admin.reports.print', [
            'report_type' => 'reservations',
        ]));

        $response->assertOk();
        $response->assertSee('Republic of the Philippines');
    }

    public function test_admin_can_access_cancellation_audit_print_view()
    {
        $response = $this->actingAs($this->admin)->get(route('admin.reports.print', [
            'view_type' => 'cancellations',
        ]));

        $response->assertOk();
        $response->assertSee('Cancellation Basis / Reason');
        $response->assertSee('Deposit Audit');
        $response->assertSee('Schedule &amp; Dates', false);
    }

    public function test_export_pdf_document_auto_generates_active_analytics_tab_with_filters()
    {
        // When clicking Export PDF from Executive Analytics with view_type=print or empty, and autoprint=1
        $response = $this->actingAs($this->admin)->get(route('admin.reports.print', [
            'report_type' => 'analytics',
            'view_type'   => 'print',
            'autoprint'   => '1',
            'date_preset' => 'all',
        ]));

        $response->assertOk();
        // Verifies the Executive Analytics view is autogenerated, not an empty table
        $response->assertSee('FACILITY &amp; REVENUE STATISTICS DASHBOARD', false);
        $response->assertSee('Total Reservations');
        $response->assertSee('Payment Settlement Breakdown');
        $response->assertSee('window.print()', false);
    }

    public function test_print_view_configures_zero_margin_page_and_flushed_repeating_footer()
    {
        $response = $this->actingAs($this->admin)->get(route('admin.reports.print', [
            'view_type' => 'table',
        ]));

        $response->assertOk();
        // 1. Ensures @page margin is 0 to disable default browser URLs and header/footer links
        $response->assertSee('margin: 0;', false);
        // 2. Ensures fixed flushed repeating footer style is present
        $response->assertSee('#docFooter {', false);
        $response->assertSee('position: fixed !important;', false);
        $response->assertSee('bottom: 0 !important;', false);
        // 3. Ensures table spacer rows exist to prevent content collision with repeating footer
        $response->assertSee('print-head-spacer', false);
        $response->assertSee('print-foot-spacer', false);
    }
}


